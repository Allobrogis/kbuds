"""Prints debian/copyright (DEP-5): this project plus one stanza per vendored crate."""
import pathlib
import sys
import tomllib

ROOT = pathlib.Path(__file__).resolve().parent.parent

HEADER = """\
Format: https://www.debian.org/doc/packaging-manuals/copyright-format/1.0/
Upstream-Name: kbuds
Source: native package
Comment: The vendor/ stanzas are generated by scripts/gen-copyright.py from the
 vendored crates' Cargo.toml. Licence texts are in each vendor/<crate>/ directory.

Files: *
Copyright: 2026 Benjamin Terrier
License: GPL-3+

"""

GPL = """\
License: GPL-3+
 This program is free software: you can redistribute it and/or modify it under
 the terms of the GNU General Public License as published by the Free Software
 Foundation, either version 3 of the License, or (at your option) any later
 version.
 .
 This program is distributed in the hope that it will be useful, but WITHOUT ANY
 WARRANTY; without even the implied warranty of MERCHANTABILITY or FITNESS FOR A
 PARTICULAR PURPOSE. See the GNU General Public License for more details.
 .
 On Debian systems, the complete text of the GNU General Public License version 3
 can be found in "/usr/share/common-licenses/GPL-3".
"""


def dep5_license(expr: str) -> str:
    # SPDX "A OR B" / "A/B" -> DEP-5 "A or B"; keep the names.
    return expr.replace("/", " OR ").replace(" OR ", " or ").replace(" AND ", " and ")


def main() -> int:
    out = [HEADER]
    names = set()
    vendor = ROOT / "vendor"
    for manifest in sorted(vendor.glob("*/Cargo.toml")):
        pkg = tomllib.loads(manifest.read_text(encoding="utf-8")).get("package", {})
        lic = pkg.get("license") or f"see {manifest.parent.name}/{pkg.get('license-file', 'LICENSE')}"
        authors = ", ".join(pkg.get("authors", [])) or f"{pkg.get('name')} authors"
        lic = dep5_license(lic)
        out.append(f"Files: vendor/{manifest.parent.name}/*\nCopyright: {authors}\nLicense: {lic}\n\n")
        for word in lic.replace("(", " ").replace(")", " ").split():
            if word not in ("or", "and", "WITH") and not word.startswith("see"):
                names.add(word)
    out.append(GPL)
    for name in sorted(names - {"GPL-3+"}):
        out.append(f"\nLicense: {name}\n See the licence file in the vendored crate directory.\n")
    sys.stdout.write("".join(out))
    return 0


if __name__ == "__main__":
    sys.exit(main())
